// 콘솔에 넘길 오류를 가볍게 만든다. 크롬은 개발자 도구가 닫혀 있어도 콘솔 메시지를 인자째 보관한다(나중에 열면
// 보여 주려고, 최대 1,000개). 그리고 V8은 오류의 스택을 처음 읽기 전까지 그 순간의 스택 프레임 — 함수와 그
// 클로저가 붙든 값 — 을 오류에 매달아 둔다. 그래서 오류 객체를 콘솔로 넘기면 던진 자리의 데이터가 통째로 남는다:
// 실측(프로덕션 번들, 개발자 도구 없음): 마크다운 파서가 스택 넘침으로 던지는 답변 하나마다 그 답변의 구문 트리
// (조상 노드 3천여 단과 위치 정보)가 RangeError에 매달린 채 약 4MB씩 남았고, 홈으로 돌아가도 풀리지 않았다
// (답 40개에 힙 164MB). 경계가 잡은 렌더 오류는 React가 스스로 console.error(오류)로 찍으므로 우리가 넘기지
// 않아도 같은 길이다.
// 스택을 한 번 읽어 두면 V8이 그것을 문자열로 만들고 프레임을 놓는다 — 콘솔에는 메시지와 스택 글자만 남는다.
export function released(error) {
  try { void error?.stack; } catch { /* 스택을 읽다 던지는 값이면 그대로 둔다 */ }
  return error;
}
